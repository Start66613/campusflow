import {spawnSync} from 'node:child_process';
import {copyFileSync,existsSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const binary='C:/Users/ASUS/.codex/skills/video-use/bin/ffmpeg.exe';
const master=path.join(root,'animations/remotion/public/audio/master.wav');
const raw=path.join(root,'audio/master-raw.wav');
if(!existsSync(raw))copyFileSync(master,raw);
const first=spawnSync(binary,['-hide_banner','-i',raw,'-af','loudnorm=I=-14:TP=-1.5:LRA=9:print_format=json','-f','null','-'],{encoding:'utf8'});
if(first.status!==0)throw new Error(first.stderr);
const stats=(source)=>{const start=source.lastIndexOf('{');return JSON.parse(source.slice(start,source.indexOf('}',start)+1));};
const m=stats(first.stderr);
const filter=`loudnorm=I=-14:TP=-1.5:LRA=9:measured_I=${m.input_i}:measured_TP=${m.input_tp}:measured_LRA=${m.input_lra}:measured_thresh=${m.input_thresh}:offset=${m.target_offset}:linear=true:print_format=json`;
const next=path.join(root,'audio/master-normalized.wav');
const second=spawnSync(binary,['-y','-hide_banner','-i',raw,'-af',filter,'-ar','48000','-ac','2','-c:a','pcm_s16le',next],{encoding:'utf8'});
if(second.status!==0)throw new Error(second.stderr);
copyFileSync(next,master);
writeFileSync(path.join(root,'audio/normalization.json'),JSON.stringify({input:m,output:stats(second.stderr)},null,2));
console.log(stats(second.stderr));
